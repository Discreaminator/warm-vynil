#!/usr/bin/env python3
"""Generate LS-fit RIAA H_play biquad tables for C++ (SPEC §4.3)."""
from __future__ import annotations

import math
from pathlib import Path

import numpy as np
from scipy.optimize import least_squares

T1, T2, T3 = 3180e-6, 318e-6, 75e-6
PI = math.pi


def analog_db(f: float) -> float:
    w = 2 * PI * f
    num = math.sqrt(1.0 + (w * T2) ** 2)
    d1 = math.sqrt(1.0 + (w * T1) ** 2)
    d2 = math.sqrt(1.0 + (w * T3) ** 2)
    return 20.0 * math.log10(num / (d1 * d2))


def biquad_db(b: np.ndarray, a: np.ndarray, f, fs: float):
    z = np.exp(-1j * 2 * PI * np.asarray(f, dtype=float) / fs)
    H = (b[0] + b[1] / z + b[2] / z**2) / (1.0 + a[0] / z + a[1] / z**2)
    return 20.0 * np.log10(np.abs(H) + 1e-300)


def fit(fs: float):
    zz = math.exp(-1.0 / (T2 * fs))
    p1 = math.exp(-1.0 / (T1 * fs))
    p3 = math.exp(-1.0 / (T3 * fs))
    a = np.array([-(p1 + p3), p1 * p3], dtype=float)
    b_init = np.array([1.0, -zz, 0.0], dtype=float)
    g = 10.0 ** (-float(biquad_db(b_init, a, 1000.0, fs)) / 20.0)
    b_init *= g

    freqs = np.geomspace(20.0, 20000.0, 400)
    targ = np.array([analog_db(float(f)) - analog_db(1000.0) for f in freqs])

    def resid(z):
        b = np.array([1.0, z[0], z[1]], dtype=float)
        gg = 10.0 ** (-float(biquad_db(b, a, 1000.0, fs)) / 20.0)
        b *= gg
        err = biquad_db(b, a, freqs, fs) - float(biquad_db(b, a, 1000.0, fs)) - targ
        return np.asarray(err, dtype=float)

    z0 = np.array([b_init[1] / b_init[0], b_init[2] / b_init[0]], dtype=float)
    res = least_squares(resid, z0, method="lm", ftol=1e-14, xtol=1e-14)
    b = np.array([1.0, res.x[0], res.x[1]], dtype=float)
    g = 10.0 ** (-float(biquad_db(b, a, 1000.0, fs)) / 20.0)
    b *= g

    ref_d = float(biquad_db(b, a, 1000.0, fs))
    ref_a = analog_db(1000.0)
    max_err = max(
        abs(float(biquad_db(b, a, float(f), fs)) - ref_d - (analog_db(float(f)) - ref_a))
        for f in np.geomspace(20.0, 20000.0, 500)
    )
    return b, a, max_err


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    out = root / "src" / "dsp" / "stages" / "RiaaCoeffs.generated.h"

    key = [88200, 96000, 176400, 192000, 352800, 384000]
    rates = sorted(
        set(key + [int(r) for r in np.geomspace(88200, 384000, 48)])
    )

    rows = []
    worst = 0.0
    for fs in rates:
        b, a, err = fit(float(fs))
        worst = max(worst, err)
        rows.append((float(fs), float(b[0]), float(b[1]), float(b[2]), float(a[0]), float(a[1]), err))
        print(f"fs={fs} maxErr={err:.4f} dB")

    lines = [
        "// Auto-generated by tools/design/riaa_reference.py — do not edit.",
        "#pragma once",
        "#include <cstddef>",
        "namespace wg::dsp::riaa_table {",
        f"inline constexpr std::size_t kN = {len(rows)};",
        "inline constexpr double kFs[kN] = {",
        ", ".join(f"{r[0]:.1f}" for r in rows) + "};",
        "inline constexpr double kB0[kN] = {",
        ", ".join(f"{r[1]:.16e}" for r in rows) + "};",
        "inline constexpr double kB1[kN] = {",
        ", ".join(f"{r[2]:.16e}" for r in rows) + "};",
        "inline constexpr double kB2[kN] = {",
        ", ".join(f"{r[3]:.16e}" for r in rows) + "};",
        "inline constexpr double kA1[kN] = {",
        ", ".join(f"{r[4]:.16e}" for r in rows) + "};",
        "inline constexpr double kA2[kN] = {",
        ", ".join(f"{r[5]:.16e}" for r in rows) + "};",
        "} // namespace wg::dsp::riaa_table",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} (worst maxErr={worst:.4f} dB)")


if __name__ == "__main__":
    main()
